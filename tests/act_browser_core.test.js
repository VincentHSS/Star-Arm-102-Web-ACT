import test from 'node:test';
import assert from 'node:assert/strict';
import {BrowserActionSchedule,validateWebManifest,validateWebCalibration,observationCoordinates,actionCoordinates,safeBrowserAction,packBrowserActCommand} from '../Browser_SDK/src/act-browser-core.js';
import { Packet } from '../Browser_SDK/src/fashionstar_serial.js';
const calibration=()=>Object.fromEntries(Array.from({length:7},(_,i)=>[i===6?'gripper':`Motor_${i}`,{id:i,range_min:100,range_max:3900,drive_mode:i%2,homing_offset:0}]));
const manifest=()=>({schema:'star-arm-browser-act-v1',model_file:'model.onnx',model_sha256:'a'.repeat(64),chunk_size:100,coordinate_contract:'degrees',joint_limits:Array.from({length:7},()=>[-180,180]),tasks:['pick'],inputs:{cameras:[0,1].map(i=>({input:`image_${i}`,feature:i?'front':'up',shape:[1,3,480,640]}))}});
test('browser model rejects missing contracts and unsupported coordinates instead of authorizing raw weights',()=>{
  assert.equal(validateWebManifest(manifest()).chunk_size,100);
  assert.throws(()=>validateWebManifest({}),/网页执行/);
  assert.throws(()=>validateWebManifest({...manifest(),coordinate_contract:'unknown'}),/坐标/);
  assert.throws(()=>validateWebManifest({...manifest(),joint_limits:[[NaN,180]]}),/限位/);
  assert.throws(()=>validateWebManifest({...manifest(),temporal_ensemble_coeff:Infinity}),/融合/);
});
test('normalized observations match the release driver double truncation and reversal',()=>{
  const result=observationCoordinates([0,18.7,-45.4,90,181,-200,45.8],calibration());
  // Reference generated by ai_service.release_adapter.ReleaseCoordinates.
  assert.deepEqual(result,[2.526315789473685,-13.26315789473685,-25.05263157894737,-56.42105263157896,100,100,64.73684210526316]);
});
test('calibration must include every physical ID and the release coordinate format',()=>{
  const data=calibration();assert.equal(validateWebCalibration(data),data);
  assert.throws(()=>validateWebCalibration({...data,Motor_2:{...data.Motor_2,id:3}}),/ID 2/);
  assert.throws(()=>validateWebCalibration({...data,Motor_0:{...data.Motor_0,homing_offset:12}}),/坐标/);
});
test('postprocessing uses release quantization and rejects nonfinite actions',()=>{
  const result=actionCoordinates([0,0,-100,100,100,-100,50],calibration());
  assert.deepEqual(result,[-4.2,-4.2,-171.2,-171.2,162.7,162.7,-4.2]);
  assert.throws(()=>actionCoordinates([0,0,0,0,0,0,NaN],calibration()),/有限/);
});
test('control bounds both physical speed and following error, and never conceals incompatible limits',()=>{
  const limits=Array.from({length:7},()=>[-100,100]);
  assert.deepEqual(safeBrowserAction(Array(7).fill(50),Array(7).fill(0),null,limits),Array(7).fill(4));
  assert.throws(()=>safeBrowserAction(Array(7).fill(0),Array(7).fill(130),null,limits),/冲突/);
});
test('time-indexed chunks skip late actions and do not burst an obsolete backlog',()=>{
  const schedule=new BrowserActionSchedule(0);
  assert.equal(schedule.add(0,Array.from({length:3},(_,i)=>Array(7).fill(i)),3),false);
  schedule.add(1,Array.from({length:4},(_,i)=>Array(7).fill(i+10)),3);
  assert.deepEqual(schedule.action(3),Array(7).fill(12));assert.equal(schedule.action(8),null);
});
test('wire frames match FashionStar multi-turn command, including gripper options and Python rounding',()=>{
  const frame=packBrowserActCommand([1.25,-1.35,2,3,4,5,6]);
  assert.deepEqual(Array.from(frame.slice(0,7)),[0x12,0x4c,25,108,14,15,7]);
  const params=frame.slice(7,-1),data=new DataView(params.buffer);
  assert.equal(data.getInt32(1,true),12);assert.equal(data.getInt32(16,true),-14);
  assert.equal(data.getUint32(5,true),350);assert.equal(data.getUint32(95,true),100);assert.equal(data.getUint16(103,true),1000);
  assert.equal(frame.at(-1),frame.slice(0,-1).reduce((n,b)=>n+b,0)&255);
  assert.throws(()=>packBrowserActCommand(Array(7).fill(Infinity)),/有限/);
});
