let currentLang = 'zh';

export function initLanguage() {
  const saved = localStorage.getItem('language');
  if (saved && translations[saved]) {
    currentLang = saved;
  } else {
    currentLang = 'zh';
  }
  document.documentElement.lang = currentLang;
}

export function setLanguage(lang) {
  if (translations[lang]) {
    currentLang = lang;
    localStorage.setItem('language', lang);
    document.documentElement.lang = lang;
    translatePage();
  }
}

export function getLanguage() {
  return currentLang;
}

export function t(key) {
  return translations[currentLang]?.[key] || translations['zh']?.[key] || key;
}

export function tWithVars(key, vars) {
  let text = t(key);
  if (vars) {
    for (const [varName, value] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${varName}\\}`, 'g'), String(value));
    }
  }
  return text;
}

export function autoTranslatePage() {
  // Additional pass for dynamically generated content
  translatePage();
}

export function translatePage() {
  // Helper function to replace only direct text nodes, preserving child elements
  function replaceTextNodes(el, translation) {
    const childNodes = Array.from(el.childNodes);
    const textNodes = childNodes.filter(node => node.nodeType === Node.TEXT_NODE);
    
    if (textNodes.length === 0) {
      // No text nodes, create one
      el.insertBefore(document.createTextNode(translation), el.firstChild);
    } else if (textNodes.length === 1) {
      // Replace the single text node
      textNodes[0].textContent = translation;
    } else {
      // Multiple text nodes - replace the first one and remove the rest
      textNodes[0].textContent = translation;
      textNodes.slice(1).forEach(node => node.remove());
    }
  }

  // Translate textContent (preserving child elements)
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    // 跳过 script、style、noscript
    if (['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(el.tagName)) return;
    const key = el.getAttribute('data-i18n');
    const translation = t(key);
    if (translation) {
      replaceTextNodes(el, translation);
    }
  });

  // Translate aria-label
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria');
    const translation = t(key);
    if (translation) {
      el.setAttribute('aria-label', translation);
    }
  });

  // Translate title
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    const translation = t(key);
    if (translation) {
      el.setAttribute('title', translation);
    }
  });

  // Translate value attribute (for inputs)
  document.querySelectorAll('[data-i18n-value]').forEach((el) => {
    const key = el.getAttribute('data-i18n-value');
    const translation = t(key);
    if (translation) {
      el.setAttribute('value', translation);
    }
  });

  // Translate placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    const translation = t(key);
    if (translation) {
      el.setAttribute('placeholder', translation);
    }
  });
}

