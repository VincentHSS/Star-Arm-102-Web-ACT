export function ss(key, vars = {}) {
  const pair = words[key];
  const value = pair?.[getLanguage() === 'en' ? 1 : 0] ?? key;
  return value.replace(/\{([^}]+)\}/g, (token, name) => Object.hasOwn(vars, name) ? String(vars[name]) : token);
}

export function servoSetupErrorMessage(error) {
  if (words[`error.${error.code}`]) return ss(`error.${error.code}`, error.details || {});
  if (error.code === 'serial_response_timeout') return ss('error.timeout');
  if (/串口.*断开|串口未连接|device.*lost|disconnected|数据流已结束/i.test(error.message)) return ss('error.disconnected');
  return error.message || ss('errorTitle');
}

